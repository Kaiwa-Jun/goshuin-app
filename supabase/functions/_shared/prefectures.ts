/** その都道府県の範囲内か。知らない都道府県名は範囲外 */
export function inPrefectureBounds(prefecture: string, lat: number, lng: number): boolean {
  const b = PREFECTURE_BOUNDS[prefecture];
  if (!b) return false;
  return !(lat < b[0] || lat > b[1] || lng < b[2] || lng > b[3]);
}
