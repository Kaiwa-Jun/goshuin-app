// el に47マスを描く。fill は {県名: "v1"|"v2"|"v3"}、now は朱で光らせる1県、
// showLabel=false ならラベルなし（小さく置くとき用）
window.renderJapan = function (el, { fill = {}, now = null, showLabel = true } = {}) {
  el.style.display = 'grid';
  el.style.gridTemplateColumns = 'repeat(11, 1fr)';
  el.style.gridTemplateRows = 'repeat(12, 1fr)';
  for (const [name, label, r, c] of window.JAPAN_TILES) {
    const t = document.createElement('i');
    t.className = 'pf' + (name === now ? ' now' : fill[name] ? ' ' + fill[name] : '');
    t.style.gridArea = r + '/' + c;
    if (showLabel) t.textContent = label;
    t.title = name;
    el.appendChild(t);
  }
};
